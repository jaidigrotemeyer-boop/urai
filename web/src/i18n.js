function erkennen() {
  const gespeichert = localStorage.getItem('urai-sprache')
  if (gespeichert && T[gespeichert]) return gespeichert
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const kurz = String(l).slice(0, 2).toLowerCase()
    if (T[kurz]) return kurz
  }
  return 'en'
}

let aktuell = erkennen()
const hoerer = new Set()

export function sprache() {
  return aktuell
}

export function setzeSprache(code) {
  if (!T[code]) return
  aktuell = code
  localStorage.setItem('urai-sprache', code)
  document.documentElement.lang = code
  hoerer.forEach((f) => f())
}

/** t('go') → 'Los'. Fehlt ein Wort, kommt Englisch. */
export function t(key) {
  return T[aktuell]?.[key] ?? T.en[key] ?? key
}

export function useSprache() {
  return useSyncExternalStore(
    (f) => {
      hoerer.add(f)
      return () => hoerer.delete(f)
    },
    () => aktuell
  )
}

document.documentElement.lang = aktuell
